m = 0.2
k = 50
A = 0.05

T = 2 * 3.141592653589793 * (m / k) ** 0.5
nu = 1 / T
omega = (k / m) ** 0.5
E_max = (k * A**2) / 2

print("ЗАДАЧА 1. ПРУЖИННЫЙ МАЯТНИК")
print()

print("УСЛОВИЕ:")
print(f"Масса груза m = {m} кг")
print(f"Жёсткость пружины k = {k} Н/м")
print(f"Амплитуда A = {A} м")
print("Найти: период T, частоту ν, циклическую частоту ω, максимальную энергию")
print()

print("РЕШЕНИЕ:")
print("Физическая основа: T = 2π·√(m/k), ω = √(k/m), E_max = k·A²/2")
print()

print("1. Период колебаний:")
print(f"   T = 2π·√(m/k) = 2·3.1416·√({m}/{k})")
print(f"   T = 2·3.1416·√({m/k:.4f})")
print(f"   T = 2·3.1416·{(m/k)**0.5:.4f}")
print(f"   T = {T:.4f} с")
print()

print("2. Частота колебаний:")
print(f"   ν = 1/T = 1/{T:.4f}")
print(f"   ν = {nu:.2f} Гц")
print()

print("3. Циклическая частота:")
print(f"   ω = √(k/m) = √({k}/{m})")
print(f"   ω = √({k/m:.0f})")
print(f"   ω = {omega:.2f} рад/с")
print()

print("4. Максимальная энергия:")
print(f"   E_max = k·A²/2 = {k}·{A}²/2")
print(f"   E_max = {k}·{A**2}/2")
print(f"   E_max = {k*A**2:.4f}/2")
print(f"   E_max = {E_max:.4f} Дж")
print()

print("ОТВЕТ:")
print(f"T = {T:.4f} с")
print(f"ν = {nu:.2f} Гц")
print(f"ω = {omega:.2f} рад/с")
print(f"E_max = {E_max:.4f} Дж")
print()

print("+-----------------------------+-----------------------------+")
print("| Параметр                    | Значение                    |")
print("+-----------------------------+-----------------------------+")
print(f"| Масса m                     | {m:>10.1f} кг              |")
print(f"| Жёсткость k                 | {k:>10.0f} Н/м             |")
print(f"| Амплитуда A                 | {A:>10.2f} м               |")
print(f"| Период T                    | {T:>10.4f} с               |")
print(f"| Частота ν                   | {nu:>10.2f} Гц             |")
print(f"| Цикл. частота ω             | {omega:>10.2f} рад/с       |")
print(f"| Макс. энергия E_max         | {E_max:>10.4f} Дж          |")
print("+-----------------------------+-----------------------------+")
print()
