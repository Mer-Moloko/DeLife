L = 1.0
g = 9.81
T_meas = 2.0
L_meas = 0.99

T_calc = 2 * 3.141592653589793 * (L / g) ** 0.5
g_from_T = (4 * 3.141592653589793**2 * L) / T_meas**2
L_from_T = (g * T_meas**2) / (4 * 3.141592653589793**2)

print("ЗАДАЧА 2. МАТЕМАТИЧЕСКИЙ МАЯТНИК")
print()
print("УСЛОВИЕ:")
print(f"Длина нити L = {L} м")
print(f"Ускорение свободного падения g = {g} м/с²")
print("Найти: период T, ускорение g по измеренному периоду, длину L по измеренному периоду")
print()

print("РЕШЕНИЕ:")
print("Физическая основа: T = 2π·√(L/g)")
print()

print("1. Период колебаний для заданного маятника:")
print(f"   T = 2π·√(L/g) = 2·3.1416·√({L}/{g})")
print(f"   T = 2·3.1416·√({L/g:.4f})")
print(f"   T = 2·3.1416·{(L/g)**0.5:.4f}")
print(f"   T = {T_calc:.4f} с")
print()

print("2. Определение g по измеренному периоду T = 2.0 с:")
print(f"   g = 4π²·L/T² = 4·3.1416²·{L}/{T_meas}²")
print(f"   g = 4·9.8696·{L}/{T_meas**2}")
print(f"   g = {4*3.1416**2*L:.2f}/{T_meas**2}")
print(f"   g = {g_from_T:.2f} м/с²")
print()

print("3. Определение L по измеренному периоду T = 2.0 с:")
print(f"   L = g·T²/(4π²) = {g}·{T_meas}²/(4·3.1416²)")
print(f"   L = {g}·{T_meas**2}/{4*3.1416**2:.2f}")
print(f"   L = {L_from_T:.4f} м")
print()

print("ОТВЕТ:")
print(f"Период T = {T_calc:.4f} с")
print(f"Ускорение g = {g_from_T:.2f} м/с² (при T = {T_meas} с)")
print(f"Длина L = {L_from_T:.4f} м (при T = {T_meas} с)")
print()

