L = 20e-3
C = 2e-6
R = 5

R_cr = 2 * (L / C) ** 0.5
oscillations_possible = R < R_cr

omega = ((1/(L*C)) - (R/(2*L))**2) ** 0.5
T = 2 * 3.141592653589793 / omega
delta = (R * T) / (2 * L)
amplitude_ratio = 2.718281828459045 ** delta

print("УСЛОВИЕ ЗАДАЧИ:")
print("В колебательном контуре с индуктивностью L = 20 мГн и ёмкостью C = 2 мкФ")
print("включено активное сопротивление R = 5 Ом")
print("1. Определите, являются ли колебания периодическими")
print("2. Найдите логарифмический декремент затухания δ")
print("3. Во сколько раз уменьшится амплитуда колебаний напряжения за время, равное одному периоду T?")
print()

print("РЕШЕНИЕ:")
print("Физическая основа:")
print("Условие возникновения колебаний: R < R_кр = 2·√(L/C)")
print("Циклическая частота затухающих колебаний: ω = √(1/(LC) - (R/(2L))²)")
print("Логарифмический декремент: δ = RT/(2L), где T = 2π/ω")
print("Уменьшение амплитуды за период: A₀/A = e^δ")
print()

print("1. Проверка условия возникновения колебаний:")
print(f"   R_кр = 2·√(L/C) = 2·√({L:.3f}/{C:.6f}) = 2·√({L/C:.2f}) = {R_cr:.2f} Ом")
print(f"   R = {R} Ом")
print(f"   {R} < {R_cr:.2f} → {'Да' if oscillations_possible else 'Нет'}")
print(f"   Колебания {'периодические' if oscillations_possible else 'апериодические'}")
print()

print("2. Найдём период и логарифмический декремент:")
print(f"   ω = √(1/({L:.3f}·{C:.6f}) - ({R}/(2·{L:.3f}))²)")
print(f"   ω = √({1/(L*C):.2f} - {R/(2*L):.2f}²)")
print(f"   ω = √({1/(L*C):.2f} - {(R/(2*L))**2:.2f})")
print(f"   ω = {omega:.2f} рад/с")
print(f"   T = 2π/ω = 2·3.1416/{omega:.2f} = {T:.6f} с = {T*1000:.2f} мс")
print(f"   δ = R·T/(2L) = {R}·{T:.6f}/(2·{L:.3f})")
print(f"   δ = {R*T:.6f}/{2*L:.3f} = {delta:.4f}")
print()

print("3. Уменьшение амплитуды за период:")
print(f"   A₀/A = e^δ = e^{delta:.4f} = {amplitude_ratio:.2f}")
print(f"   Амплитуда уменьшится в {amplitude_ratio:.2f} раз(а)")
print()

print("ОТВЕТ:")
print(f"1. R_кр = {R_cr:.2f} Ом, R = {R} Ом → колебания {'периодические' if oscillations_possible else 'апериодические'}")
print(f"2. δ = {delta:.4f}")
print(f"3. Амплитуда уменьшится в {amplitude_ratio:.2f} раз(а)")
print()

print("+-----------------------------+---------------------------+")
print("| Параметр                    | Значение                  |")
print("+-----------------------------+---------------------------+")
print(f"| Индуктивность L             | {L*1000:>10.0f} мГн       |")
print(f"| Ёмкость C                   | {C*1e6:>10.0f} мкФ        |")
print(f"| Сопротивление R             | {R:>10.1f} Ом            |")
print(f"| Критическое сопротивление   | {R_cr:>10.2f} Ом         |")
print(f"| Колебания возможны          | {'Да' if oscillations_possible else 'Нет':>10}         |")
print(f"| Период T                    | {T*1000:>10.2f} мс        |")
print(f"| Логарифмический декремент δ | {delta:>10.4f}           |")
print(f"| Уменьшение амплитуды за T   | {amplitude_ratio:>10.2f} раз |")
print("+-----------------------------+---------------------------+")