Ac = 10
Am = 4
nu_c = 1e6
nu_m = 1e3

M = Am / Ac

nu_upper = nu_c + nu_m
nu_lower = nu_c - nu_m

U_max = Ac * (1 + M)
U_min = Ac * (1 - M)

print("УСЛОВИЕ ЗАДАЧИ:")
print("Высокочастотный несущий сигнал: u_нес(t) = Ac·cos(2π·νc·t)")
print(f"где Ac = {Ac} В, νc = {nu_c/1e6} МГц")
print("Низкочастотный информационный сигнал: u_инф(t) = Am·cos(2π·νm·t)")
print(f"где Am = {Am} В, νm = {nu_m/1e3} кГц")
print("1. Запишите уравнение амплитудно-модулированного сигнала u_АМ(t)")
print("2. Какие частоты входят в спектр модулированного сигнала?")
print("3. Вычислите максимальное и минимальное значение огибающей")
print()

print("РЕШЕНИЕ:")
print("Физическая основа:")
print("Уравнение АМ-сигнала: u_АМ(t) = Ac·[1 + M·cos(2π·νm·t)]·cos(2π·νc·t)")
print("где M = Am/Ac — коэффициент модуляции")
print("Спектр АМ-сигнала содержит три частоты:")
print("  - несущая: νc")
print("  - верхняя боковая: νc + νm")
print("  - нижняя боковая: νc - νm")
print()

print("1. Найдём коэффициент модуляции:")
print(f"   M = Am/Ac = {Am}/{Ac} = {M:.2f}")
print(f"   Уравнение АМ-сигнала:")
print(f"   u_АМ(t) = {Ac}·[1 + {M:.2f}·cos(2π·{nu_m/1e3}·t)]·cos(2π·{nu_c/1e6}·t)")
print()

print("2. Частоты в спектре модулированного сигнала:")
print(f"   Несущая частота: νc = {nu_c/1e6:.3f} МГц ({nu_c:.0f} Гц)")
print(f"   Верхняя боковая: νc + νm = {nu_c/1e6:.3f} + {nu_m/1e3:.3f} = {(nu_c+nu_m)/1e6:.6f} МГц ({nu_upper:.0f} Гц)")
print(f"   Нижняя боковая: νc - νm = {nu_c/1e6:.3f} - {nu_m/1e3:.3f} = {(nu_c-nu_m)/1e6:.6f} МГц ({nu_lower:.0f} Гц)")
print()

print("3. Максимальное и минимальное значение огибающей:")
print(f"   U_макс = Ac·(1 + M) = {Ac}·(1 + {M:.2f}) = {Ac}·{1+M:.2f} = {U_max:.2f} В")
print(f"   U_мин = Ac·(1 - M) = {Ac}·(1 - {M:.2f}) = {Ac}·{1-M:.2f} = {U_min:.2f} В")
print()

print("ОТВЕТ:")
print(f"1. u_АМ(t) = {Ac}·[1 + {M:.2f}·cos(2π·{nu_m/1e3}·t)]·cos(2π·{nu_c/1e6}·t)")
print(f"2. Спектр: {nu_c/1e6:.3f} МГц, {(nu_c+nu_m)/1e6:.6f} МГц, {(nu_c-nu_m)/1e6:.6f} МГц")
print(f"3. U_макс = {U_max:.2f} В, U_мин = {U_min:.2f} В")
print()

