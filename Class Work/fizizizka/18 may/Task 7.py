L = 0.5
C = 20e-6
R = 10
U = 220

omega_res = 1 / ((L * C) ** 0.5)
nu_res = omega_res / (2 * 3.141592653589793)
I_res = U / R
XC = 1 / (omega_res * C)
UC = I_res * XC
Q_factor = UC / U

print("УСЛОВИЕ ЗАДАЧИ:")
print("Последовательная цепь переменного тока состоит из:")
print(f"катушки индуктивностью L = {L} Гн,")
print(f"конденсатора ёмкостью C = {C*1e6} мкФ,")
print(f"резистора сопротивлением R = {R} Ом.")
print(f"Цепь подключена к источнику переменного напряжения U = {U} В.")
print("1. При какой частоте ν_res в цепи наступит резонанс напряжений?")
print("2. Чему равно действующее значение силы тока I_res при резонансе?")
print("3. Каково напряжение на конденсаторе U_C при резонансе?")
print()

print("РЕШЕНИЕ:")
print("Физическая основа:")
print("Резонанс наступает, когда индуктивное сопротивление равно ёмкостному:")
print("ω_res·L = 1/(ω_res·C) → ω_res = 1/√(LC)")
print("При резонансе полное сопротивление Z = R")
print("Ток: I_res = U/R")
print("Напряжение на конденсаторе: U_C = I_res·X_C = I_res·(1/(ω_res·C))")
print()

print("1. Найдём резонансную частоту:")
print(f"   ω_res = 1/√(L·C) = 1/√({L}·{C})")
print(f"   ω_res = 1/√({L*C:.2e}) = {omega_res:.2f} рад/с")
print(f"   ν_res = ω_res/(2π) = {omega_res:.2f}/(2·3.1416)")
print(f"   ν_res = {nu_res:.2f} Гц")
print()

print("2. Найдём силу тока при резонансе:")
print(f"   I_res = U/R = {U}/{R} = {I_res:.2f} А")
print()

print("3. Найдём напряжение на конденсаторе:")
print(f"   X_C = 1/(ω_res·C) = 1/({omega_res:.2f}·{C})")
print(f"   X_C = {XC:.2f} Ом")
print(f"   U_C = I_res·X_C = {I_res:.2f}·{XC:.2f}")
print(f"   U_C = {UC:.2f} В")
print()

print("Дополнительно - добротность контура:")
print(f"   Q = U_C/U = {UC:.2f}/{U} = {Q_factor:.2f}")
print(f"   Напряжение на конденсаторе превышает напряжение источника в {Q_factor:.2f} раз(а)")
print()

print("ОТВЕТ:")
print(f"1. Резонансная частота ν_res = {nu_res:.2f} Гц")
print(f"2. Сила тока при резонансе I_res = {I_res:.2f} А")
print(f"3. Напряжение на конденсаторе U_C = {UC:.2f} В")
print(f"   (превышает напряжение источника в {Q_factor:.2f} раз(а))")
print()

