import math

R_z = 6370
h = 200
T_min = 88

R_orb = R_z + h
R_orb_m = R_orb * 1000
T_s = T_min * 60
omega = 2 * math.pi / T_s
V = omega * R_orb_m
V_km_s = V / 1000
a_cs = V**2 / R_orb_m
L = 2 * math.pi * R_orb
N = 24 * 60 / T_min

print("ЗАДАЧА 4.2: СПУТНИК ЗЕМЛИ")
print()
print("УСЛОВИЕ:")
print(f"Радиус Земли R_з = {R_z} км")
print(f"Высота спутника над Землёй h = {h} км")
print(f"Период обращения T = {T_min} мин")
print("Найти: радиус орбиты, угловую и линейную скорость,")
print("центростремительное ускорение, длину орбиты, число оборотов за сутки")
print()

print("РЕШЕНИЕ:")
print()

print("1. Радиус орбиты спутника:")
print(f"   R_орб = R_з + h = {R_z} + {h} = {R_orb} км")
print(f"   R_орб = {R_orb_m} м")
print()

print("2. Период в секундах:")
print(f"   T_с = T·60 = {T_min}·60 = {T_s} с")
print()

print("3. Угловая скорость спутника:")
print(f"   ω = 2π/T_с = 2·3.1416/{T_s}")
print(f"   ω = {omega:.6f} рад/с")
print()

print("4. Линейная скорость спутника:")
print(f"   V = ω·R_орб = {omega:.6f}·{R_orb_m}")
print(f"   V = {V:.2f} м/с = {V_km_s:.2f} км/с")
print()

print("5. Центростремительное ускорение:")
print(f"   a_цс = V²/R_орб = {V:.2f}²/{R_orb_m}")
print(f"   a_цс = {a_cs:.2f} м/с²")
print()

print("6. Длина орбиты спутника:")
print(f"   L = 2π·R_орб = 2·3.1416·{R_orb}")
print(f"   L = {L:.2f} км")
print()

print("7. Количество оборотов за сутки:")
print(f"   N = 24·60/T = 1440/{T_min}")
print(f"   N = {N:.2f} оборота за сутки")
print()

print("Проверка:")
print(f"   Первая космическая скорость для h = {h} км: около 7.8 км/с")
print(f"   Получено: V = {V_km_s:.2f} км/с")
print(f"   Период для низкой орбиты: 88-90 мин")
print(f"   Получено: T = {T_min} мин")
print()

print("ОТВЕТ:")
print(f"Радиус орбиты R_орб = {R_orb} км ({R_orb_m} м)")
print(f"Угловая скорость ω = {omega:.6f} рад/с")
print(f"Линейная скорость V = {V:.2f} м/с ({V_km_s:.2f} км/с)")
print(f"Центростремительное ускорение a_цс = {a_cs:.2f} м/с²")
print(f"Длина орбиты L = {L:.2f} км")
print(f"Число оборотов за сутки N = {N:.2f}")
print()

