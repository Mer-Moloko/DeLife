L_km = 384400
c_ms = 3e8
L_m = L_km * 1000
t = L_m / c_ms

t0_str = "12:00:00"
h, m, s = map(int, t0_str.split(':'))
total_seconds = h * 3600 + m * 60 + s
real_total = total_seconds - t
real_h = int(real_total // 3600)
real_m = int((real_total % 3600) // 60)
real_s = real_total % 60
real_time_str = f"{real_h:02d}:{real_m:02d}:{real_s:05.2f}"

