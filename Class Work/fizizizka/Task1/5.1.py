print()

print("   Время распространения света:")
print(f"   t = L / c = {L_m} / {c_ms} = {t:.4f} с")
print(f"   t ≈ {t:.2f} с ≈ {t/60:.2f} мин")
print()

print("2. Наблюдаемое время: t0 = 12:00:00")
print("   Реальное время = t0 - t (так как мы видим с задержкой)")
print(f"   t0 = {total_seconds} секунд от полуночи")
print(f"   t = {t:.2f} с")
print(f"   Реальное время в секундах = {total_seconds} - {t:.2f} = {real_total:.2f} с")
print()

print("   Переведём обратно в часы:минуты:секунды")
