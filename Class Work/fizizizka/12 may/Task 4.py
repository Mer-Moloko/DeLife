h1 = 100
h2 = 10
R = 6400e3

d1 = (2 * R * h1) ** 0.5
d2 = (2 * R * h2) ** 0.5
D = d1 + d2
D_km = D / 1000

print("УСЛОВИЕ ЗАДАЧИ:")
print(f"Высота передающей антенны h1 = {h1} м")
print(f"Высота приёмной антенны h2 = {h2} м")
print("Оцените максимальную дальность прямой видимости D между антеннами,")
print(f"считая Землю шаром радиусом R = {R/1000} км")
print()

print("РЕШЕНИЕ:")
print("Физическая основа:")
print("Электромагнитные волны УКВ-диапазона распространяются прямолинейно.")
print("Из-за кривизны Земли дальность связи ограничена горизонтом.")
print("Расстояние до горизонта для антенны высотой h: d = √(2Rh)")
print("Полная дальность: D = √(2Rh1) + √(2Rh2)")
print()

print("1. Расстояние до горизонта от передающей антенны:")
print(f"   d1 = √(2·R·h1) = √(2·{R/1000}·{h1})")
print(f"   d1 = √({2*R*h1:.2f})")
print(f"   d1 = {d1:.2f} м = {d1/1000:.2f} км")
print()

print("2. Расстояние до горизонта от приёмной антенны:")
print(f"   d2 = √(2·R·h2) = √(2·{R/1000}·{h2})")
print(f"   d2 = √({2*R*h2:.2f})")
print(f"   d2 = {d2:.2f} м = {d2/1000:.2f} км")
print()

print("3. Максимальная дальность прямой видимости:")
print(f"   D = d1 + d2 = {d1:.2f} + {d2:.2f}")
print(f"   D = {D:.2f} м = {D_km:.2f} км")
print()

print("ОТВЕТ:")
print(f"Максимальная дальность прямой видимости D = {D_km:.2f} км")
print()

