lam = 300
L = 10e-3
c = 3e8

C = lam**2 / (4 * 3.141592653589793**2 * c**2 * L)
C_pF = C * 1e12

print("УСЛОВИЕ ЗАДАЧИ:")
print(f"Радиоприемник настроен на длину волны λ = {lam} м")
print(f"Индуктивность катушки приемного контура L = {L*1000} мГн")
print("Какой ёмкости C должен быть конденсатор в этом контуре?")
print("Скорость распространения электромагнитных волн c = 3·10⁸ м/с")
print()

print("РЕШЕНИЕ:")
print("Физическая основа:")
print("Длина волны связана с частотой и скоростью света:")
print("λ = c·T = c/ν")
print("Частота настройки контура определяется формулой Томсона:")
print("ν = 1/(2π·√(LC))")
print("Объединяя формулы, получаем связь длины волны с параметрами контура:")
print("λ = c·2π·√(LC)")
print("Выразим ёмкость C:")
print("√(LC) = λ/(2πc) → LC = (λ/(2πc))² → C = λ²/(4π²c²L)")
print()

print("1. Найдём необходимую ёмкость:")
print(f"   C = λ²/(4π²·c²·L)")
print(f"   C = {lam}²/(4·3.1416²·({c})²·{L})")
print(f"   C = {lam**2}/(4·9.8696·{c**2:.2e}·{L})")
print(f"   C = {lam**2}/({4*3.1416**2*c**2*L:.2e})")
print(f"   C = {C:.3e} Ф")
print(f"   C = {C_pF:.2f} пФ")
print()

print("ОТВЕТ:")
print(f"Для настройки на длину волны λ = {lam} м")
print(f"при индуктивности L = {L*1000} мГн")
print(f"необходима ёмкость C = {C_pF:.2f} пФ ({C:.3e} Ф)")
print()

