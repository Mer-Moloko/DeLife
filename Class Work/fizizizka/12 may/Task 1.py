C = 2e-6
L = 0.5

T = 2 * 3.141592653589793 * ((L * C) ** 0.5)
nu = 1 / T

print("УСЛОВИЕ ЗАДАЧИ:")
print("Колебательный контур состоит из конденсатора ёмкостью C = 2 мкФ")
print("и катушки индуктивностью L = 0.5 Гн")
print("Определите период T собственных свободных электромагнитных колебаний")
print("в контуре и их частоту ν. Сопротивлением контура пренебречь.")
print()

print("РЕШЕНИЕ:")
print("Физическая основа:")
print("Период свободных колебаний определяется формулой Томсона:")
print("T = 2π·√(L·C)")
print("Частота связана с периодом: ν = 1/T")
print()

print("1. Найдём период колебаний:")
print(f"   T = 2π·√(L·C) = 2·3.1416·√({L}·{C})")
print(f"   T = 2·3.1416·√({L*C:.2e})")
print(f"   T = 2·3.1416·{(L*C)**0.5:.4f}")
print(f"   T = {T:.6f} с")
print(f"   T = {T*1000:.2f} мс")
print()

print("2. Найдём частоту колебаний:")
print(f"   ν = 1/T = 1/{T:.6f}")
print(f"   ν = {nu:.2f} Гц")
print()

print("ОТВЕТ:")
print(f"Период колебаний T = {T:.4f} с ({T*1000:.2f} мс)")
print(f"Частота колебаний ν = {nu:.2f} Гц")
print()

print("+-----------------------------+-----------------------------+")
print("| Параметр                    | Значение                    |")
print("+-----------------------------+-----------------------------+")
