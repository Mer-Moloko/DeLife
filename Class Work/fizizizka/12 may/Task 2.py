U_max = 100
C = 10e-6
L = 0.1

W = (C * U_max**2) / 2
I_max = (2 * W / L) ** 0.5

print("УСЛОВИЕ ЗАДАЧИ:")
print("В идеальном колебательном контуре максимальное напряжение")
print(f"на конденсаторе равно U_max = {U_max} В")
print(f"Ёмкость конденсатора C = {C*1e6} мкФ")
print("Найдите полную энергию электромагнитного поля в контуре")
print(f"и амплитудное значение силы тока I_max, если L = {L} Гн")
print()

print("РЕШЕНИЕ:")
print("Физическая основа:")
print("Полная энергия W в идеальном контуре сохраняется и равна")
print("максимальной энергии электрического поля конденсатора:")
print("W = C·U²/2")
print("Также полная энергия равна максимальной энергии магнитного поля катушки:")
print("W = L·I²/2")
print("Отсюда I_max = √(2W/L) = U_max·√(C/L)")
print()

print("1. Найдём полную энергию контура:")
print(f"   W = C·U_max²/2 = {C}·{U_max}²/2")
print(f"   W = {C}·{U_max**2}/2")
print(f"   W = {C*U_max**2:.4f}/2")
print(f"   W = {W:.4f} Дж")
print(f"   W = {W*1000:.2f} мДж")
print()

print("2. Найдём амплитудное значение силы тока:")
print(f"   I_max = √(2W/L) = √(2·{W:.4f}/{L})")
print(f"   I_max = √({2*W:.4f}/{L})")
print(f"   I_max = √({2*W/L:.4f})")
print(f"   I_max = {I_max:.4f} А")
print()

print("Проверка через соотношение U_max·√(C/L):")
print(f"   I_max = {U_max}·√({C}/{L})")
print(f"   I_max = {U_max}·√({C/L:.4f})")
print(f"   I_max = {U_max}·{(C/L)**0.5:.4f}")
print(f"   I_max = {I_max:.4f} А")
print()

print("ОТВЕТ:")
print(f"Полная энергия контура W = {W:.4f} Дж ({W*1000:.2f} мДж)")
print(f"Амплитуда силы тока I_max = {I_max:.4f} А")
print()

