print("| Параметр                    | Значение                    |")
print("+-----------------------------+-----------------------------+")
print(f"| Макс. напряжение U_max      | {U_max:>10.0f} В           |")
print(f"| Ёмкость C                   | {C*1e6:>10.0f} мкФ          |")
print(f"| Индуктивность L             | {L:>10.1f} Гн              |")
print(f"| Полная энергия W            | {W:>10.4f} Дж              |")
print(f"| Полная энергия W            | {W*1000:>10.2f} мДж        |")
print(f"| Амплитуда тока I_max        | {I_max:>10.4f} А           |")
print("+-----------------------------+-----------------------------+")