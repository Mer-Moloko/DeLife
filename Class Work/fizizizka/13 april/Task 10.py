U = 50
R1 = 2
R2 = 6
U3 = 10

R12 = R1 + R2
U12 = U - U3
I = U12 / R12
R3 = U3 / I
U1 = I * R1
U2 = I * R2

print("УСЛОВИЕ ЗАДАЧИ:")
print("Участок цепи состоит из трёх последовательно соединённых проводников,")
print(f"подключённых к источнику напряжения U = {U} В")
print(f"Сопротивление первого проводника R1 = {R1} Ом")
print(f"Сопротивление второго проводника R2 = {R2} Ом")
print(f"Напряжение на третьем проводнике U3 = {U3} В")
print("Найти: силу тока I, сопротивление R3, напряжения U1 и U2")
print()

print("РЕШЕНИЕ:")
print("Физическая основа:")
print("При последовательном соединении: I = const, U = U1 + U2 + U3, R = R1 + R2 + R3")
print("Закон Ома: U = I·R")
print()

print("1. Найдём напряжение на первом и втором проводниках вместе:")
print(f"   U12 = U - U3 = {U} - {U3} = {U12} В")
print()

print("2. Найдём общее сопротивление первого и второго проводников:")
print(f"   R12 = R1 + R2 = {R1} + {R2} = {R12} Ом")
print()

print("3. Найдём силу тока в цепи:")
print(f"   I = U12 / R12 = {U12} / {R12} = {I:.2f} А")
print()

print("4. Найдём сопротивление третьего проводника:")
print(f"   R3 = U3 / I = {U3} / {I:.2f} = {R3:.2f} Ом")
print()

print("5. Найдём напряжения на первом и втором проводниках:")
print(f"   U1 = I·R1 = {I:.2f}·{R1} = {U1:.2f} В")
print(f"   U2 = I·R2 = {I:.2f}·{R2} = {U2:.2f} В")
print()

print("Проверка:")
print(f"   U = U1 + U2 + U3 = {U1:.2f} + {U2:.2f} + {U3} = {U1+U2+U3:.2f} В")
print(f"   R = R1 + R2 + R3 = {R1} + {R2} + {R3:.2f} = {R1+R2+R3:.2f} Ом")
print(f"   U = I·R = {I:.2f}·{R1+R2+R3:.2f} = {I*(R1+R2+R3):.2f} В")
print()

print("ОТВЕТ:")
print(f"Сила тока I = {I:.2f} А")
print(f"Сопротивление третьего проводника R3 = {R3:.2f} Ом")
print(f"Напряжение на первом проводнике U1 = {U1:.2f} В")
print(f"Напряжение на втором проводнике U2 = {U2:.2f} В")
print()

