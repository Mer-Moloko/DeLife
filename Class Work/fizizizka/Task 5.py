print("Задача: Меднение монетки (закон Фарадея)")
print("Дано:\n"
      "\tСила тока А - 0.5\n"
      "\tВремя, с (30 минут) - 1800\n"
      "\tЭлектрохимический эквивалент меди, кг/Кл - 3.29e-7\n"
      "\tПлощадь поверхности монетки, м² (5 см² = 0.0005 м²) - 5e-4\n"
      "\tплотность меди, кг/м³ - 8900\n")
I = 0.5          # сила тока, А
t = 1800         # время, с (30 минут)
k = 3.29e-7      # электрохимический эквивалент меди, кг/Кл
S = 5e-4         # площадь поверхности монетки, м² (5 см² = 0.0005 м²)
rho = 8900       # плотность меди, кг/м³


m_kg = k * I * t
m_g = m_kg * 1000

print("-"*60)

print("Использованные формулы:")
print()
print("1. Закон Фарадея для электролиза:")
print("   m = k * I * t")
print("   где:")
print("       m — масса выделившегося вещества (кг)")
print("       k — электрохимический эквивалент (кг/Кл)")
print("       I — сила тока (А)")
print("       t — время (с)")
print()
print("2. Перевод массы из кг в г:")
print("   m_г = m_кг * 1000")
print()
print("3. Объём через плотность:")
print("   V = m / ρ")
print("   где:")
print("       V — объём (м³)")
print("       ρ — плотность (кг/м³)")
print()
print("4. Толщина равномерного покрытия:")
print("   h = V / S")
print("   где:")
print("       h — толщина (м)")
print("       S — площадь покрытия (м²)")
print()
print("5. Перевод толщины в мм и мкм:")
print("   h_мм = h_м * 1000")
print("   h_мкм = h_мм * 1000")
print("-"*60)
print("\nОтвет:")
print("\t1. Масса меди, выделившейся на катоде:")
print(f"   m = {m_kg:.3e} кг = {m_g:.3f} г")


V = m_kg / rho
h_m = V / S
h_mm = h_m * 1000
h_um = h_mm * 1000

print("\t2. Толщина медного покрытия:")
print(f"   h = {h_m:.3e} м = {h_mm:.4f} мм = {h_um:.1f} мкм")