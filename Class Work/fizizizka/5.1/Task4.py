F_cm = 15
H_cm = 5
d_cm = 40

f_cm = 1 / ((1/F_cm) - (1/d_cm))
Gamma = f_cm / d_cm
h_cm = Gamma * H_cm

image_type = "Действительное" if f_cm > 0 else "Мнимое"
orientation = "Перевёрнутое" if Gamma < 0 else "Прямое"
size = "Увеличенное" if abs(Gamma) > 1 else "Уменьшенное" if abs(Gamma) < 1 else "Равное"

print("УСЛОВИЕ ЗАДАЧИ:")
print("Собирающая линза имеет фокусное расстояние F = 15 см")
print("Предмет высотой H = 5 см расположен на расстоянии d = 40 см от линзы")
print("1. Найдите расстояние до изображения f")
print("2. Определите высоту изображения h и увеличение линзы Γ")
print("3. Каким будет изображение (действительное/мнимое, прямое/перевёрнутое, увеличенное/уменьшенное)?")
print()

print("РЕШЕНИЕ:")
print("Физическая основа:")
print("Формула тонкой линзы: 1/F = 1/d + 1/f")
print("Увеличение линзы: Γ = h/H = f/d")
print()

print("1. Найдём расстояние до изображения:")
print(f"   1/f = 1/F - 1/d")
print(f"   1/f = 1/{F_cm} - 1/{d_cm}")
print(f"   1/f = {1/F_cm:.4f} - {1/d_cm:.4f} = {1/F_cm - 1/d_cm:.4f}")
print(f"   f = {f_cm:.2f} см")
print()

print("2. Определим увеличение и высоту изображения:")
print(f"   Γ = f/d = {f_cm:.2f}/{d_cm} = {Gamma:.2f}")
print(f"   h = Γ · H = {Gamma:.2f} · {H_cm} = {h_cm:.2f} см")
print()

print("3. Характеристики изображения:")
print(f"   - f = {f_cm:.2f} см > 0 → {image_type}")
print(f"   - Γ = {Gamma:.2f} > 0 → {orientation}")
print(f"   - |Γ| = {abs(Gamma):.2f} {'> 1 → Увеличенное' if abs(Gamma) > 1 else '< 1 → Уменьшенное' if abs(Gamma) < 1 else '= 1 → Равное'}")
print()

print("ОТВЕТ:")
print(f"1. Расстояние до изображения: f = {f_cm:.2f} см")
print(f"2. Увеличение: Γ = {Gamma:.2f}, высота изображения: h = {h_cm:.2f} см")
print(f"3. Изображение: {image_type.lower()}, {orientation.lower()}, {size.lower()}")
print()

